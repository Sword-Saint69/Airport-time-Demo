/** True when the cell at (col,row) is land. */
export function isLand(col: number, row: number): boolean {
  if (row < 0 || row >= MAP_ROWS || col < 0 || col >= MAP_COLS) return false;
  return WORLD_ROWS[row].charCodeAt(col) === 49; // '1'
}

/**
 * Project a longitude/latitude to fractional grid coordinates in the
 * dot-matrix map. Uses the same equirectangular mapping as WORLD_ROWS.
 */
export function project(lat: number, lon: number): { col: number; row: number } {
  const col = ((lon + 180) / 360) * MAP_COLS;
  const row = ((LAT_MAX - lat) / (LAT_MAX - LAT_MIN)) * MAP_ROWS;
  return { col, row };
}

/** Number of land cells in the bitmap (for a debug label). */
export function landCellCount(): number {
  let count = 0;
  for (let row = 0; row < MAP_ROWS; row++) {
    const line = WORLD_ROWS[row];
    for (let col = 0; col < MAP_COLS; col++) {
      if (line.charCodeAt(col) === 49) count++;
    }
  }
  return count;
}
