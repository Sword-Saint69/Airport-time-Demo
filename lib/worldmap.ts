/**
 * A fine dot-matrix world map.
 *
 * MAP_COLS x MAP_ROWS cells describe the whole world in an equirectangular
 * projection: longitude -180..180 maps to columns 0..MAP_COLS and latitude
 * LAT_MAX..LAT_MIN maps to rows 0..MAP_ROWS, row 0 being the northern edge.
 * '1' = land, '0' = ocean.
 *
 * The bitmap is rasterised from Natural Earth 50m land polygons
 * (ne_50m_land.geojson, https://github.com/nvkelso/natural-earth-vector).
 * Every cell is the intersection of the land geometry with the cell's
 * geographic rectangle; a cell counts as land when at least 30% of its area is
 * covered by land, which keeps thin peninsulas and island chains visible
 * instead of dropping them. Antarctica is clipped away at LAT_MIN.
 *
 * Isolated specks (components of fewer than 3 cells) are then removed so the
 * map does not show stray dots in open ocean. Connectivity is 8-way: with
 * 4-way connectivity diagonal landmasses such as Italy's boot, Cuba, the
 * Philippine arc and New Zealand's south island break into two-cell fragments
 * that the same rule would delete, which loses real land.
 */

/** Number of columns in the dot-matrix map. */
export const MAP_COLS: number = 150;

/** Number of rows in the dot-matrix map. */
export const MAP_ROWS: number = 75;

/** Northern edge of the map in degrees latitude. */
export const LAT_MAX: number = 84;

/** Southern edge of the map in degrees latitude. */
export const LAT_MIN: number = -60;

